export function getCardEffectiveStats(card: PlayerCard, level: number) {
  const bonus = Math.max(0, level - 1) * 3;
  return {
    pace: Math.min(99, card.baseStats.pace + bonus),
    shooting: Math.min(99, card.baseStats.shooting + bonus),
    passing: Math.min(99, card.baseStats.passing + bonus),
    tackling: Math.min(99, card.baseStats.tackling + bonus),
    ovr: Math.min(
      99,
      Math.round(
        (card.baseStats.pace + card.baseStats.shooting + card.baseStats.passing + card.baseStats.tackling) / 4 + bonus
      )
    ),
  };
}

export function getUpgradeCostCoins(level: number, rarity: RarityTier): number {
  const mult = rarity === 'Mythical' ? 2.2 : rarity === 'Legendary' ? 1.8 : rarity === 'Epic' ? 1.5 : rarity === 'Rare' ? 1.25 : 1;
  return Math.round(150 * level * mult);
}

